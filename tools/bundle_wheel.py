"""
Builds openNVE wheels with neuromorphic_drivers embedded.

For each neuromorphic_drivers wheel (one per platform and Python version), this script
creates an openNVE wheel with the same tags that contains:

- the opennve package (from this repository)
- the neuromorphic_drivers package (Python files and the compiled extension, unchanged)
- the console scripts of both (opennve, ndls, neuromorphic-drivers-install-*)
- the licenses of both

Usage:
    python tools/bundle_wheel.py NEUROMORPHIC_DRIVERS_WHEEL_OR_DIRECTORY... --out dist [--min-python 3.14]
"""

from __future__ import annotations

import argparse
import base64
import datetime
import email.parser
import hashlib
import os
import pathlib
import re
import sys
import tomllib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
TAG_PATTERN = re.compile(r"^cp(\d)(\d+)$")



def _build_date() -> datetime.datetime:
    """Build date (UTC): OPENNVE_BUILD_DATE (ISO date / time) or SOURCE_DATE_EPOCH if set, else now.
    The build number is <day of year>.<year> of this date."""
    if os.environ.get("OPENNVE_BUILD_DATE"):
        value = datetime.datetime.fromisoformat(os.environ["OPENNVE_BUILD_DATE"])
        return value if value.tzinfo else value.replace(tzinfo=datetime.timezone.utc)
    if os.environ.get("SOURCE_DATE_EPOCH"):
        return datetime.datetime.fromtimestamp(int(os.environ["SOURCE_DATE_EPOCH"]), datetime.timezone.utc)
    return datetime.datetime.now(datetime.timezone.utc).replace(microsecond=0)

def record_hash(data: bytes) -> str:
    digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()
    return f"sha256={digest}"


def wheel_tags(path: pathlib.Path) -> tuple[str, str, str]:
    # name-version(-build)?-python-abi-platform.whl
    parts = path.stem.split("-")
    return parts[-3], parts[-2], parts[-1]


def python_version_of(tag: str) -> tuple[int, int] | None:
    match = TAG_PATTERN.match(tag)
    if match is None:
        return None
    return int(match.group(1)), int(match.group(2))


def read_project() -> dict:
    return tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]


def bundle(nd_wheel: pathlib.Path, out: pathlib.Path) -> pathlib.Path:
    project = read_project()
    name = project["name"]
    version = project["version"]
    python_tag, abi_tag, platform_tag = wheel_tags(nd_wheel)
    dist_info = f"{name}-{version}.dist-info"
    files: dict[str, bytes] = {}

    with zipfile.ZipFile(nd_wheel) as source:
        nd_dist_info = next(
            entry.split("/")[0] for entry in source.namelist() if entry.split("/")[0].endswith(".dist-info")
        )
        nd_metadata = email.parser.Parser().parsestr(source.read(f"{nd_dist_info}/METADATA").decode())
        nd_version = nd_metadata["Version"]
        nd_entry_points = source.read(f"{nd_dist_info}/entry_points.txt").decode()
        nd_wheel_info = email.parser.Parser().parsestr(source.read(f"{nd_dist_info}/WHEEL").decode())
        for entry in source.infolist():
            if entry.is_dir():
                continue
            top = entry.filename.split("/")[0]
            if top == nd_dist_info:
                if "/licenses/" in entry.filename:
                    license_name = entry.filename.split("/licenses/", 1)[1]
                    files[f"{dist_info}/licenses/neuromorphic_drivers/{license_name}"] = source.read(entry)
                continue
            files[entry.filename] = source.read(entry)

    # opennve package
    for path in sorted((ROOT / "opennve").rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        files[path.relative_to(ROOT).as_posix()] = path.read_bytes()
    build_date = _build_date()
    files["opennve/_bundle.py"] = (
        '"""Generated by tools/bundle_wheel.py."""\n\n'
        f'NEUROMORPHIC_DRIVERS_VERSION = "{nd_version}"\n'
        f'BUILD_DATE = "{build_date.isoformat(timespec="seconds")}"\n'
        f'BUILD_NUMBER = "{build_date.timetuple().tm_yday}.{build_date.year}"\n'
    ).encode()
    for license_path in (ROOT / "LICENSE", ROOT / "LICENSE.md", ROOT / "LICENSE.txt"):
        if license_path.is_file():
            files[f"{dist_info}/licenses/{license_path.name}"] = license_path.read_bytes()

    # Metadata: opennve dependencies without neuromorphic_drivers (embedded), plus its dependencies
    requirements = [
        requirement
        for requirement in project.get("dependencies", [])
        if not requirement.replace("-", "_").lower().startswith("neuromorphic_drivers")
    ]
    for requirement in nd_metadata.get_all("Requires-Dist") or []:
        if requirement.split(";")[0].replace(" ", "") not in [r.replace(" ", "") for r in requirements]:
            requirements.append(requirement)
    lines = [
        "Metadata-Version: 2.1",
        f"Name: {name}",
        f"Version: {version}",
        f"Summary: {project.get('description', '')}",
        f"Requires-Python: {project.get('requires-python', '>=3.14')}",
    ]
    lines += [f"Requires-Dist: {requirement}" for requirement in requirements]
    for extra, extra_requirements in project.get("optional-dependencies", {}).items():
        lines.append(f"Provides-Extra: {extra}")
        for requirement in extra_requirements:
            requirement, _, marker = requirement.partition(";")
            marker = f'({marker.strip()}) and extra == "{extra}"' if marker.strip() else f'extra == "{extra}"'
            lines.append(f"Requires-Dist: {requirement.strip()}; {marker}")
    lines += [
        "Description-Content-Type: text/markdown",
        "",
        f"Bundled with neuromorphic_drivers {nd_version} (MIT License, licenses/neuromorphic_drivers).",
        "",
        (ROOT / "README.md").read_text(encoding="utf-8"),
    ]
    files[f"{dist_info}/METADATA"] = "\n".join(lines).encode()

    tags = nd_wheel_info.get_all("Tag") or [f"{python_tag}-{abi_tag}-{platform_tag}"]
    files[f"{dist_info}/WHEEL"] = (
        "Wheel-Version: 1.0\nGenerator: openNVE bundle_wheel.py\nRoot-Is-Purelib: false\n"
        + "".join(f"Tag: {tag}\n" for tag in tags)
    ).encode()

    scripts = [f"{script} = {target}" for script, target in project.get("scripts", {}).items()]
    nd_scripts = nd_entry_points.split("[console_scripts]", 1)[-1].strip().splitlines()
    files[f"{dist_info}/entry_points.txt"] = (
        "[console_scripts]\n" + "\n".join(scripts + [line for line in nd_scripts if line.strip()]) + "\n"
    ).encode()

    record_name = f"{dist_info}/RECORD"
    record = "".join(f"{path},{record_hash(data)},{len(data)}\n" for path, data in files.items())
    record += f"{record_name},,\n"
    files[record_name] = record.encode()

    out.mkdir(parents=True, exist_ok=True)
    output = out / f"{name}-{version}-{python_tag}-{abi_tag}-{platform_tag}.whl"
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as target:
        # dist-info last, as recommended by the wheel specification
        for path in sorted(files, key=lambda path: (path.startswith(dist_info), path)):
            target.writestr(zipfile.ZipInfo(path, date_time=(2020, 1, 1, 0, 0, 0)), files[path])
    return output


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("inputs", nargs="+", type=pathlib.Path, help="neuromorphic_drivers wheels or directories")
    parser.add_argument("--out", type=pathlib.Path, default=ROOT / "dist")
    parser.add_argument("--min-python", default="3.14", help="skip wheels for older Python versions")
    parser.add_argument("--free-threaded", action="store_true", help="also bundle free-threaded (cp3XXt) wheels")
    args = parser.parse_args()
    minimum = tuple(int(part) for part in args.min_python.split("."))

    wheels = []
    for path in args.inputs:
        wheels += sorted(path.glob("neuromorphic_drivers-*.whl")) if path.is_dir() else [path]
    count = 0
    for wheel in wheels:
        python_tag, abi_tag, _ = wheel_tags(wheel)
        version = python_version_of(python_tag)
        if version is None or version < minimum or (abi_tag.endswith("t") and not args.free_threaded):
            print(f"skipped {wheel.name}")
            continue
        print(f"{wheel.name} -> {bundle(wheel, args.out).name}")
        count += 1
    if count == 0:
        print("error: no matching neuromorphic_drivers wheel", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
